package ru.yamshchik.yamshchik.config.properties;


public enum RateLimitStrategy {

    /**
     * Без ограничения: письма уходят так быстро, как успевают обработчики.
     */
    NONE,

    /**
     * Постоянный темп, заданный настройкой.
     */
    FIXED,

    /**
     * Темп подстраивается под ответы сервера: растёт понемногу, пока сервер принимает,
     * и резко падает, когда сервер просит сбавить (AIMD).
     */
    AIMD
}
