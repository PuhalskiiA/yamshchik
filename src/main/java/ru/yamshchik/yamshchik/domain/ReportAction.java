package ru.yamshchik.yamshchik.domain;

/**
 * Действие из отчёта о доставке (RFC 3464, поле Action).
 */
public enum ReportAction {

    /**
     * Доставлено в ящик получателя.
     */
    DELIVERED,

    /**
     * Передано серверу, который отчётов не присылает: дальнейшая судьба письма неизвестна.
     */
    RELAYED,

    /**
     * Доставлено и разослано дальше, например по списку рассылки.
     */
    EXPANDED,

    /**
     * Сервер пока не смог доставить и продолжает попытки сам.
     */
    DELAYED,

    /**
     * Сервер отказался от доставки.
     */
    FAILED
}
