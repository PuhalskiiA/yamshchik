package ru.yamshchik.yamshchik.domain;

/**
 * Состояние доставки письма одному получателю.
 */
public enum DeliveryStatus {

    /**
     * Почтовый сервер ещё не принял письмо для этого получателя: ждёт первой отправки или повторной.
     */
    PENDING,

    /**
     * Сервер принял письмо, отчёт о доставке ещё не пришёл.
     */
    SENT,

    /**
     * Сервер сообщил, что письмо доставлено или передано дальше.
     */
    DELIVERED,

    /**
     * Доставить не удалось, попыток больше не будет.
     */
    UNDELIVERED
}
